function answerStatus(value) {
  if (value === 'yes') return 'confirmed';
  if (value === 'no') return 'blocked';
  return 'pending';
}

function assessCount(value, [minimum, maximum]) {
  const count = Number(value);
  let status = 'pending';
  if (Number.isInteger(count) && count > 0) {
    const withinRange = count >= minimum && (maximum === null || count <= maximum);
    status = withinRange ? 'confirmed' : 'blocked';
  }
  const range = maximum === null ? `от ${minimum}` : `от ${minimum} до ${maximum}`;
  return {
    id: 'count',
    label: 'Допустимое число участников',
    help: `Требуемое число участников: ${range}.`,
    status,
  };
}

export function assessSpecial(key, answers) {
  if (!Object.hasOwn(specialProfiles, key)) {
    return { status: 'unknown', checks: [], steps: ['Выберите специальный статус.'] };
  }
  const profile = specialProfiles[key];
  const checks = profile.checks.map(check => ({
    ...check,
    status: answerStatus(answers[`special_${check.id}`]),
  }));

  if (profile.count) checks.push(assessCount(answers.special_count, profile.count));
  let status = 'preliminary';
  if (checks.some(check => check.status === 'blocked')) status = 'blocked';
  else if (checks.some(check => check.status === 'pending')) status = 'pending';

  return { status, checks, steps: profile.steps, economic: profile.economic, source: profile.source };
}
